# --- Провайдеры / сервис ---


def normalize_lang(code: str | None) -> str:
    """Привести код из запроса/сессии к ru | kk | en."""
    if not code:
        return DEFAULT_LANG
    code = str(code).strip().lower()
    if code in ("kz", "kk", "kaz"):
        return "kk"
    if code in ("en", "eng"):
        return "en"
    if code in ("ru", "rus"):
        return "ru"
    return DEFAULT_LANG if code not in SUPPORTED else code


class CatalogProvider:
    """UI-строки из словаря TRANSLATIONS. Текущий бэкенд по умолчанию."""

    mode = "catalog"

    def translate(self, lang: str, key: str, **kwargs) -> str:
        lang = normalize_lang(lang)
        text = TRANSLATIONS.get(lang, {}).get(key)
        if text is None:
            text = TRANSLATIONS[DEFAULT_LANG].get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, ValueError):
                return text
        return text

    def bundle(self, lang: str) -> dict[str, str]:
        lang = normalize_lang(lang)
        out = dict(TRANSLATIONS[DEFAULT_LANG])
        out.update(TRANSLATIONS.get(lang, {}))
        return out

    def translate_dynamic(
        self,
        text: str,
        target_lang: str,
        source_lang: str | None = None,
    ) -> str:
        """Свободный текст (чат, уведомления). Catalog-режим: без изменений.

        Позже можно сменить на ApiMtProvider (DeepL / LibreTranslate)
        без правок вызывающего кода — уже через TranslationService.
        """
        return text


class ApiMtProvider(CatalogProvider):
    """Заглушка машинного перевода свободного текста.

    UI-ключи остаются в CatalogProvider.translate(); для MT
    переопределите translate_dynamic() под внешний API.
    Включите I18N_PROVIDER=api и задайте endpoint/key.
    """

    mode = "api"

    def __init__(self, endpoint: str | None = None, api_key: str | None = None):
        self.endpoint = endpoint
        self.api_key = api_key

    def translate_dynamic(
        self,
        text: str,
        target_lang: str,
        source_lang: str | None = None,
    ) -> str:
        # Пока не подключено — возвращаем исходный текст.
        # При включении: POST text + langs на self.endpoint.
        return text


class TranslationService:
    """Единая точка входа для UI-ключей и (в будущем) динамического MT."""

    def __init__(self, provider: CatalogProvider | None = None):
        self.provider = provider or CatalogProvider()

    @property
    def mode(self) -> str:
        return getattr(self.provider, "mode", "catalog")

    def t(self, lang: str, key: str, **kwargs) -> str:
        return self.provider.translate(lang, key, **kwargs)

    def bundle(self, lang: str) -> dict[str, str]:
        return self.provider.bundle(lang)

    def translate_dynamic(
        self,
        text: str,
        target_lang: str,
        source_lang: str | None = None,
    ) -> str:
        if not text:
            return text
        target = normalize_lang(target_lang)
        source = normalize_lang(source_lang) if source_lang else None
        if source and source == target:
            return text
        return self.provider.translate_dynamic(text, target, source)


def _build_service() -> TranslationService:
    import os

    mode = (os.environ.get("I18N_PROVIDER") or "catalog").strip().lower()
    if mode == "api":
        return TranslationService(
            ApiMtProvider(
                endpoint=os.environ.get("I18N_MT_ENDPOINT"),
                api_key=os.environ.get("I18N_MT_API_KEY"),
            )
        )
    return TranslationService(CatalogProvider())


i18n = _build_service()


