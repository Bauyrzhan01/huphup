def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", text.lower()) or "demo"


def main():
    existing = []
    if USERS_FILE.exists():
        existing = json.loads(USERS_FILE.read_text(encoding="utf-8"))

    # Keep real users, replace previous demos
    users = [
        u
        for u in existing
        if not str(u.get("email", "")).endswith("@tenderbauka.kz")
    ]

    n = 0
    for cat in CATEGORIES:
        for i, (company, person, desc) in enumerate(COMPANIES[cat]):
            n += 1
            email = f"demo.{slugify(company)}@tenderbauka.kz"
            while any(u["email"] == email for u in users):
                n += 1
                email = f"demo.{n:03d}@tenderbauka.kz"

            addr = CITIES[(n + i) % len(CITIES)]
            bank = BANKS[(n + i) % len(BANKS)]
            users.append(
                {
                    "id": str(uuid.uuid4()),
                    "role": "supplier",
                    "name": person,
                    "email": email,
                    "password": pwd_hash,
                    "created_at": datetime.utcnow().isoformat() + "Z",
                    "supplier": {
                        "company_name": company,
                        "bin": f"{100000000000 + n:012d}",
                        "legal_address": addr[0],
                        "actual_address": addr[1],
                        "phone": f"+7 701 {7000000 + n:07d}",
                        "contact_person": person,
                        "bank_name": bank,
                        "iban": f"KZ86125KZT{100000000000 + n:012d}",
                        "bik": f"HSBK{1000 + (n % 8000)}",
                        "category": cat,
                        "description": desc,
                        "website": f"https://example.kz/{slugify(company)}",
                        "years_on_market": str(3 + (n % 15)),
                    },
                }
            )

    USERS_FILE.write_text(
        json.dumps(users, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    demo_count = sum(1 for u in users if u["email"].endswith("@tenderbauka.kz"))
    print(f"Total users: {len(users)}, demo suppliers: {demo_count}")
    print(f"Password for all demos: {PASSWORD}")
    counts = Counter(
        u["supplier"]["category"]
        for u in users
        if u.get("role") == "supplier" and "supplier" in u
    )
    for cat in CATEGORIES:
        print(f"  {cat}: {counts.get(cat, 0)}")


if __name__ == "__main__":
    main()
